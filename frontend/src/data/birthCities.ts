// 출생지역 드롭다운용 대표 도시 데이터. 국적(countries.ts의 `ko` 값)을 키로 한다.
// 모든 도시를 넣지 않고, "시차(표준시 UTC offset)를 결정하는 대표 도시"만 담는다 —
// 단일 시간대 국가는 수도 1곳, 여러 시간대를 가진 국가(미국·러시아·캐나다·호주 등)는
// 시간대별 대표 도시를 나열한다.
//
// offset은 "표준시" 기준(서머타임 미적용)이며, 영구적으로 DST를 폐지/고정한 국가는 현재 상시값을 쓴다.
// 소수는 30/45분 시차를 뜻한다(예: 인도 5.5 = +5:30, 네팔 5.75 = +5:45).
export interface BirthCity {
  ko: string;
  en: string;
  /** 표준시 UTC offset(시간 단위, 소수 허용: 5.5=+5:30, -3.5=-3:30). */
  offset: number;
}

// 항상 "시:분" 형식으로 표기한다("+9:00", "+5:30", "-5:00", "±0:00").
export function formatUtcOffset(offset: number): string {
  const sign = offset > 0 ? "+" : offset < 0 ? "-" : "±";
  const abs = Math.abs(offset);
  const hours = Math.trunc(abs);
  const minutes = Math.round((abs - hours) * 60);
  return `${sign}${hours}:${String(minutes).padStart(2, "0")}`;
}

